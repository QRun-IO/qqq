/*******************************************************************************
 ** Two independent runners contend on real H2 keys, with no shared JVM monitor.
 *******************************************************************************/
class RDBMSHealthTest
{
   private QInstance instance;
   private RDBMSBackendMetaData backend;



   /*******************************************************************************
    ** Real SQL schema includes the non-null scheduled request discriminator.
    *******************************************************************************/
   @BeforeEach
   void setUp() throws Exception
   {
      backend = TestUtils.defineBackend().withJdbcUrl("jdbc:h2:mem:health_" + UUID.randomUUID() + ";DB_CLOSE_DELAY=-1;DATABASE_TO_UPPER=FALSE");
      instance = TestUtils.defineInstance();
      instance.getBackends().put(backend.getName(), backend);
      new HealthMetaDataProvider().defineAll(instance, backend.getName(), table -> table.withBackendDetails(new RDBMSTableBackendDetails().withTableName(table.getName())));
      new QInstanceEnricher(instance).enrich();
      QContext.init(instance, new QSession().withPermissions("health.read", "health.write"));
      try(Connection connection = ConnectionManager.getConnection(backend); Statement statement = connection.createStatement())
      {
         statement.execute("""
            CREATE TABLE health_check (
               id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
               name VARCHAR(255) UNIQUE, label VARCHAR(255), component VARCHAR(255), category VARCHAR(255), kind VARCHAR(255), severity VARCHAR(255),
               current_status VARCHAR(255), current_message VARCHAR(500), recent_transitions_json VARCHAR(65536),
               interval_seconds INTEGER, timeout_ms INTEGER, failure_threshold INTEGER, recovery_threshold INTEGER,
               consecutive_failures INTEGER, consecutive_successes INTEGER, last_latency_ms BIGINT,
               enabled BOOLEAN DEFAULT TRUE, registered BOOLEAN, flapping BOOLEAN,
               current_since TIMESTAMP, last_run_at TIMESTAMP, next_due_at TIMESTAMP)
            """);
         statement.execute("""
            CREATE TABLE health_check_result (
               id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, health_check_id INTEGER NOT NULL,
               slot BIGINT NOT NULL, on_demand_request_id VARCHAR(255) NOT NULL DEFAULT '',
               status VARCHAR(255), message VARCHAR(500), details_json VARCHAR(4096), metrics_json VARCHAR(65536),
               latency_ms BIGINT, started_at TIMESTAMP, finished_at TIMESTAMP, runner_pod VARCHAR(255),
               lease_expires_at TIMESTAMP, is_transition BOOLEAN, triggered_by VARCHAR(255),
               UNIQUE (health_check_id, slot, on_demand_request_id))
            """);
         statement.execute("CREATE INDEX health_result_started ON health_check_result (health_check_id, started_at)");
         statement.execute("""
            CREATE TABLE health_component (
               id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(255) UNIQUE, label VARCHAR(255), status VARCHAR(255),
               since TIMESTAMP, checks_up INTEGER, checks_degraded INTEGER, checks_down INTEGER, checks_unknown INTEGER,
               worst_check_id INTEGER, updated_at TIMESTAMP)
            """);
      }
   }



   /*******************************************************************************
    ** Release JDBC pools and thread context after each isolated database.
    *******************************************************************************/
   @AfterEach
   void tearDown()
   {
      ConnectionManager.resetConnectionProviders();
      QContext.clear();
   }



   /*******************************************************************************
    ** Registered backend check exposes vendor only, including broken-source errors.
    *******************************************************************************/
   @Test
   void databaseRegistrationAndRedaction() throws Exception
   {
      var check = HealthChecksMetaData.ofOrWithNew(instance).getChecks().stream()
         .filter(definition -> definition.getName().equals("core.database." + backend.getName())).findFirst().orElseThrow();
      assertThat(check.getKind()).isEqualTo(HealthCheckKind.READINESS);
      assertThat(check.getIncludeInReadiness()).isTrue();
      var outcome = check.getCheckInstance().run(new HealthCheckInput().withQInstance(instance).withDeadline(Instant.now().plusSeconds(3)));
      assertThat(outcome.getStatus()).isEqualTo(HealthStatus.UP);
      assertThat(outcome.getDetails().getValues()).containsOnlyKeys("vendor").containsEntry("vendor", "h2");
      ConnectionManager.resetConnectionProviders();
      backend.setJdbcUrl("jdbc:invalid:password=sentinelCredential");
      outcome = check.getCheckInstance().run(new HealthCheckInput().withQInstance(instance).withDeadline(Instant.now().plusSeconds(3)));
      assertThat(outcome.getStatus()).isEqualTo(HealthStatus.DOWN);
      assertThat(outcome.getMessage()).doesNotContain("sentinelCredential");
      assertThat(outcome.getDetails().getValues()).isEmpty();
   }



   /*******************************************************************************
    ** Repeated simultaneous ticks prove the SQL key decides ownership. A separate
    ** monitor per call explicitly prevents MEMORY_LOCK from masking this race.
    *******************************************************************************/
   @Test
   void twoPodsClaimExactlyOnceAndRecoverAbandonedLease() throws Exception
   {
      AtomicInteger runs = new AtomicInteger();
      instance.withSupplementalMetaData(new HealthChecksMetaData().withCheck(new HealthCheckMetaData()
         .withName("test.race").withComponent("test").withIntervalSeconds(10).withTimeoutMs(1000).withCheckInstance(new HealthCheck()
         {


            /*******************************************************************
             ** Count executions independently of persisted result rows.
             *******************************************************************/
            @Override
            public HealthCheckOutcome run(HealthCheckInput input)
            {
               runs.incrementAndGet();
               return (HealthCheckOutcome.up("Healthy"));
            }
         })));
      assertThat(HealthStore.lockFor(instance)).isNotSameAs(HealthStore.lockFor(instance)).isNotSameAs(HealthStore.MEMORY_LOCK);
      Instant start = Instant.parse("2026-10-14T12:00:00Z");
      var time = new AtomicReference<>(start);
      Clock clock = new Clock()
      {
         /***********************************************************************
          ** All pods observe the same deterministic slot clock.
          ***********************************************************************/
         @Override
         public ZoneId getZone()
         {
            return (ZoneOffset.UTC);
         }



         /***********************************************************************
          ** Tests use UTC only.
          ***********************************************************************/
         @Override
         public Clock withZone(ZoneId zone)
         {
            return (this);
         }



         /***********************************************************************
          ** Advance between simultaneous ticks, never during an execution.
          ***********************************************************************/
         @Override
         public Instant instant()
         {
            return (time.get());
         }
      };
      try(HealthRunner podA = new HealthRunner(instance, "A", clock).withRandom(new Random(1));
          HealthRunner podB = new HealthRunner(instance, "B", clock).withRandom(new Random(1));
          var threads = Executors.newFixedThreadPool(2))
      {
         for(int i = 0; i < 30; i++)
         {
            time.set(start.plusSeconds(i * 10L + 2));
            CountDownLatch ready = new CountDownLatch(2);
            CountDownLatch go = new CountDownLatch(1);
            var first = threads.submit(() -> tickTogether(podA, ready, go));
            var second = threads.submit(() -> tickTogether(podB, ready, go));
            assertThat(ready.await(5, TimeUnit.SECONDS)).isTrue();
            go.countDown();
            first.get(10, TimeUnit.SECONDS);
            second.get(10, TimeUnit.SECONDS);
         }
      }
      List<QRecord> results = HealthStore.query(HealthMetaDataProvider.RESULT_TABLE, new QQueryFilter());
      assertThat(results).hasSize(30);
      assertThat(runs).hasValue(30);
      assertThat(results.stream().map(row -> row.getValueLong("slot")).distinct()).hasSize(30);
      assertThat(results).allSatisfy(row -> assertThat(row.getValueString("onDemandRequestId")).isEmpty());
      QRecord check = HealthStore.find(HealthMetaDataProvider.CHECK_TABLE, "name", "test.race");
      QRecord abandoned = HealthStore.insert(HealthMetaDataProvider.RESULT_TABLE, new QRecord()
         .withValue("healthCheckId", check.getValue("id")).withValue("slot", start.plusSeconds(300).getEpochSecond() / 10)
         .withValue("onDemandRequestId", "").withValue("status", "RUNNING").withValue("runnerPod", "A")
         .withValue("startedAt", start.plusSeconds(300)).withValue("leaseExpiresAt", start.plusSeconds(306)));
      try(HealthRunner survivor = new HealthRunner(instance, "B", Clock.fixed(start.plusSeconds(312), ZoneOffset.UTC)))
      {
         survivor.tick();
      }
      QRecord closed = HealthStore.find(HealthMetaDataProvider.RESULT_TABLE, "id", abandoned.getValue("id"));
      assertThat(closed.getValueString("status")).isEqualTo("UNKNOWN");
      assertThat(closed.getValueString("message")).isEqualTo("abandoned by pod A");
      assertThat(HealthStore.query(HealthMetaDataProvider.RESULT_TABLE, new QQueryFilter())).hasSize(32);
      assertThat(runs).hasValue(31);
      QRecord next = HealthStore.find(HealthMetaDataProvider.RESULT_TABLE, "slot", start.plusSeconds(312).getEpochSecond() / 10);
      assertThat(next.getValueString("runnerPod")).isEqualTo("B");
      assertThat(next.getValueString("status")).isEqualTo("UP");
   }



   /*******************************************************************************
    ** Separate worker threads rendezvous immediately before their ticks.
    *******************************************************************************/
   private void tickTogether(HealthRunner runner, CountDownLatch ready, CountDownLatch go)
   {
      ready.countDown();
      try
      {
         if(!go.await(5, TimeUnit.SECONDS))
         {
            throw new IllegalStateException("Race start timed out");
         }
         runner.tick();
      }
      catch(InterruptedException e)
      {
         Thread.currentThread().interrupt();
         throw new IllegalStateException(e);
      }
   }
}
